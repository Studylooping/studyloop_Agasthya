import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadSource } from "./lib/source-loader.mjs";

const { VIDEO_SELECTIONS } = loadSource("content/video-selections");
const { VIDEO_METADATA } = loadSource("content/video-metadata");
const { COURSES } = loadSource("content/courses");
const refresh = process.argv.includes("--refresh");
const refreshMissing = process.argv.includes("--refresh-missing");
const network = refresh || refreshMissing || process.argv.includes("--network");
const metadata = refreshMissing ? { ...VIDEO_METADATA } : {};
const seen = new Set();
const networkErrors = [];
const courseFilter = process.argv
  .find((arg) => arg.startsWith("--course="))
  ?.slice(9);
for (const lesson of VIDEO_SELECTIONS) {
  assert.match(lesson.videoId, /^[A-Za-z0-9_-]{11}$/);
  const key = `${lesson.courseSlug}/${lesson.unitSlug}/${lesson.videoId}`;
  assert.ok(!seen.has(key), `Duplicate selection: ${key}`);
  seen.add(key);
  const course = COURSES.find((c) => c.slug === lesson.courseSlug);
  const unit = course?.units.find((u) => u.slug === lesson.unitSlug);
  assert.ok(unit, `Missing unit: ${key}`);
  assert.ok(lesson.topicCodes.length > 0, `No topics: ${key}`);
  assert.equal(
    new Set(lesson.topicCodes).size,
    lesson.topicCodes.length,
    `Repeated topic: ${key}`,
  );
  for (const code of lesson.topicCodes)
    assert.ok(
      unit.topics.some((t) => t.topicCode === code),
      `Unknown topic ${code}: ${key}`,
    );
  assert.ok(lesson.coverage.length > 30, `Missing scope: ${key}`);
  assert.ok(["en", "hi"].includes(lesson.language));
  assert.ok(["concept", "lesson", "revision"].includes(lesson.format));
}
// Validate every mapping before making availability requests.
for (const lesson of VIDEO_SELECTIONS) {
  const key = `${lesson.courseSlug}/${lesson.unitSlug}/${lesson.videoId}`;
  if (network && !metadata[lesson.videoId]) {
    const url = new URL("https://www.youtube.com/oembed");
    url.search = new URLSearchParams({
      url: `https://www.youtube.com/watch?v=${lesson.videoId}`,
      format: "json",
    }).toString();
    let res;
    try {
      res = await fetch(url, { signal: AbortSignal.timeout(20000) });
    } catch (error) {
      networkErrors.push(`${lesson.videoId}: ${error.message}`);
      continue;
    }
    if (!res.ok) {
      networkErrors.push(`${lesson.videoId}: oEmbed returned ${res.status}`);
      delete metadata[lesson.videoId];
      continue;
    }
    const data = await res.json();
    assert.equal(data.provider_name, "YouTube");
    assert.ok(
      data.title &&
        data.author_name &&
        data.html?.includes("youtube.com/embed/"),
    );
    metadata[lesson.videoId] = {
      title: data.title,
      channel: data.author_name,
      checkedOn: new Date().toISOString().slice(0, 10),
    };
    if (!process.argv.includes("--quiet"))
      console.log(`${lesson.videoId}: ${data.author_name} | ${data.title}`);
  } else if (!network) {
    assert.ok(
      VIDEO_METADATA[lesson.videoId]?.title,
      `Metadata missing: ${key}`,
    );
  }
}
if (refresh || refreshMissing) {
  const source = `import type { VideoMetadata } from "@/lib/video-lessons";\n\n// Generated by scripts/check-video-lessons.mjs --refresh; no student-side metadata requests.\nexport const VIDEO_METADATA: Record<string, VideoMetadata> = ${JSON.stringify(metadata, null, 2)};\n`;
  writeFileSync(resolve("content/video-metadata.ts"), source, "utf8");
}
assert.deepEqual(
  networkErrors,
  [],
  "Some selected videos could not be verified",
);
const mapped = new Set(
  VIDEO_SELECTIONS.map((v) => `${v.courseSlug}/${v.unitSlug}`),
);
for (const key of mapped) {
  const languages = new Set(
    VIDEO_SELECTIONS.filter((v) => `${v.courseSlug}/${v.unitSlug}` === key).map(
      (v) => v.language,
    ),
  );
  assert.deepEqual(
    [...languages].sort(),
    ["en", "hi"],
    `Missing language: ${key}`,
  );
}
console.log(
  `PASS: ${VIDEO_SELECTIONS.length} scoped selections across ${mapped.size} units, each with both language options.`,
);
console.log(
  "Metadata availability is not a full academic review or a guarantee of regional playback. Unmapped units remain without video claims.",
);
const gaps = [];
let topicCount = 0;
for (const course of COURSES.filter(
  (c) => c.status === "live" && (!courseFilter || c.slug === courseFilter),
)) {
  for (const unit of course.units.filter((u) => u.status === "live")) {
    for (const topic of unit.topics.filter((t) => t.items.length > 0)) {
      topicCount += 1;
      for (const language of ["en", "hi"]) {
        if (
          !VIDEO_SELECTIONS.some(
            (v) =>
              v.courseSlug === course.slug &&
              v.unitSlug === unit.slug &&
              v.language === language &&
              v.topicCodes.includes(topic.topicCode),
          )
        ) {
          gaps.push(
            `${course.slug}/${unit.slug} | ${topic.topicCode} ${topic.title} | ${language}`,
          );
        }
      }
    }
  }
}
console.log(
  `Topic-language mappings: ${topicCount * 2 - gaps.length}/${topicCount * 2}; ${gaps.length} gaps.`,
);
if (process.argv.includes("--coverage")) console.log(gaps.join("\n"));
if (process.argv.includes("--require-complete"))
  assert.equal(
    gaps.length,
    0,
    "Some live topics still lack a mapped lesson in one or both languages",
  );
